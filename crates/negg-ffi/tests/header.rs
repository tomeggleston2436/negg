//! The committed header `include/negg.h` is the one cbindgen generates
//! (Ruling 88). `NEGG_BLESS=1 cargo test -p negg-ffi --test header`
//! rewrites it.

use std::path::PathBuf;

fn generate() -> String {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let config = cbindgen::Config {
        language: cbindgen::Language::C,
        include_guard: Some("NEGG_H".to_owned()),
        pragma_once: false,
        cpp_compat: true,
        sys_includes: vec!["stdint.h".into(), "stddef.h".into()],
        no_includes: true,
        usize_is_size_t: true,
        header: Some(
            "/* SPDX-License-Identifier: Apache-2.0 */\n/* Generated by cbindgen from crates/negg-ffi. Do not edit. */"
                .to_owned(),
        ),
        enumeration: cbindgen::EnumConfig {
            prefix_with_name: true,
            ..Default::default()
        },
        documentation_style: cbindgen::DocumentationStyle::C,
        ..Default::default()
    };
    let bindings = cbindgen::Builder::new()
        .with_crate(&dir)
        .with_config(config)
        .generate()
        .expect("cbindgen");
    let mut out = Vec::new();
    bindings.write(&mut out);
    String::from_utf8(out).unwrap()
}

#[test]
fn header_is_current() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("include/negg.h");
    let fresh = generate();
    if std::env::var_os("NEGG_BLESS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &fresh).unwrap();
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        committed == fresh,
        "include/negg.h is stale; run `NEGG_BLESS=1 cargo test -p negg-ffi --test header`"
    );
}
