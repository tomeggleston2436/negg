//! C ABI over the negg engine (phase 3, Rulings 67 and 88).
//!
//! Owns the foreign-function boundary only. Must not contain engine
//! maths; it wraps `negg-session`. The rules of the ABI:
//!
//! - Every function returns a [`NeggStatus`] (except the few that cannot
//!   fail) and never unwinds into the caller: each body runs under
//!   `catch_unwind`, a caught panic returns [`NeggStatus::Panic`] and
//!   poisons the session handle, after which every call on it returns
//!   [`NeggStatus::Poisoned`].
//! - Every pointer argument is checked for NULL ([`NeggStatus::Null`]).
//! - A handle may be used from any thread; calls on one handle are
//!   serialised by an internal mutex. A call can block for a long time:
//!   [`negg_open_roll`] analyses the whole roll and [`negg_export`] decodes
//!   and renders every frame (minutes for a large roll), and any other call
//!   on the same handle waits for them. Call them off a UI thread.
//! - Edits are written to the sidecars by the setters themselves (each
//!   commits and then flushes), by [`negg_flush`], and by a best-effort
//!   flush in [`negg_session_free`].
//! - Strings returned by negg are freed only with [`negg_string_free`].
//! - The message of the last failure on the calling thread is read with
//!   [`negg_last_error`].
//! - JSON carries settings and statistics only, never pixels. Tiles use the
//!   binary format of `negg_session::wire`.
//!
//! The header is `include/negg.h`, generated by cbindgen; a test fails when
//! it is stale (`NEGG_BLESS=1 cargo test -p negg-ffi` rewrites it).

use std::cell::RefCell;
use std::ffi::{CStr, CString, c_char};
use std::panic::{AssertUnwindSafe, catch_unwind};
use std::path::Path;
use std::sync::Mutex;
use std::sync::atomic::{AtomicBool, Ordering};

use negg_session::{AnalyseStep, ExportFormat, ExportRequest, ExportScope, Session, SessionError};
use negg_types::{FrameOverrides, RollSettings};

/// The version of this C ABI; bumped on any incompatible change.
pub const NEGG_ABI_VERSION: u32 = 1;

/// The result of every fallible call. `Ok` is zero.
#[repr(i32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NeggStatus {
    /// Success.
    Ok = 0,
    /// A required pointer argument was NULL.
    Null = 1,
    /// A string argument was not valid UTF-8.
    Utf8 = 2,
    /// A JSON argument could not be parsed or a result could not be built.
    Json = 3,
    /// The frame index is outside the roll.
    NotFound = 4,
    /// The caller's buffer is too small; the size needed is written to
    /// `*len`.
    BufferTooSmall = 5,
    /// The session refused or failed the call; see [`negg_last_error`].
    Session = 6,
    /// A panic was caught; the session is poisoned.
    Panic = 7,
    /// The session was poisoned by an earlier panic.
    Poisoned = 8,
}

/// An open roll: the session behind a mutex plus the poisoned flag. Opaque
/// to C.
pub struct NeggSession {
    inner: Mutex<Session>,
    poisoned: AtomicBool,
}

thread_local! {
    static LAST_ERROR: RefCell<String> = const { RefCell::new(String::new()) };
}

fn set_error(msg: impl Into<String>) {
    let msg = msg.into();
    LAST_ERROR.with(|e| *e.borrow_mut() = msg);
}

fn fail(status: NeggStatus, msg: impl Into<String>) -> NeggStatus {
    set_error(msg);
    status
}

fn session_status(e: &SessionError) -> NeggStatus {
    set_error(e.to_string());
    match e {
        SessionError::NoFrame(_) => NeggStatus::NotFound,
        _ => NeggStatus::Session,
    }
}

/// Runs `f` so that no panic escapes. A caught panic is a [`NeggStatus::Panic`].
fn guard(f: impl FnOnce() -> Result<(), NeggStatus>) -> NeggStatus {
    match catch_unwind(AssertUnwindSafe(f)) {
        Ok(Ok(())) => NeggStatus::Ok,
        Ok(Err(s)) => s,
        Err(_) => fail(NeggStatus::Panic, "internal error: a panic was caught"),
    }
}

/// Runs `f` on the locked session of `s`, poisoning the handle on a panic.
fn with_session<T>(
    s: *const NeggSession,
    f: impl FnOnce(&mut Session) -> Result<T, NeggStatus>,
) -> Result<T, NeggStatus> {
    // SAFETY: the caller of the extern function promised `s` is NULL or a
    // live handle from `negg_open_roll`.
    let h = unsafe { s.as_ref() }.ok_or_else(|| fail(NeggStatus::Null, "session is NULL"))?;
    if h.poisoned.load(Ordering::SeqCst) {
        return Err(fail(
            NeggStatus::Poisoned,
            "the session was poisoned by a panic",
        ));
    }
    let r = catch_unwind(AssertUnwindSafe(|| {
        let mut g = h.inner.lock().map_err(|_| NeggStatus::Poisoned)?;
        f(&mut g)
    }));
    match r {
        Ok(Ok(v)) => Ok(v),
        Ok(Err(NeggStatus::Poisoned)) => {
            h.poisoned.store(true, Ordering::SeqCst);
            Err(fail(
                NeggStatus::Poisoned,
                "the session was poisoned by a panic",
            ))
        }
        Ok(Err(status)) => Err(status),
        Err(_) => {
            h.poisoned.store(true, Ordering::SeqCst);
            Err(fail(
                NeggStatus::Panic,
                "internal error: a panic was caught; the session is poisoned",
            ))
        }
    }
}

/// A NULL-checked, UTF-8-checked borrowed C string.
///
/// # Safety
///
/// `p` is NULL or points to a NUL-terminated string that outlives `'a`.
unsafe fn c_str<'a>(p: *const c_char, what: &str) -> Result<&'a str, NeggStatus> {
    if p.is_null() {
        return Err(fail(NeggStatus::Null, format!("{what} is NULL")));
    }
    // SAFETY: non-NULL and NUL-terminated by the caller's contract.
    let c = unsafe { CStr::from_ptr(p) };
    c.to_str()
        .map_err(|_| fail(NeggStatus::Utf8, format!("{what} is not valid UTF-8")))
}

/// Hands `s` to the caller through `out`.
///
/// # Safety
///
/// `out` is a valid, writable `*mut c_char` location.
unsafe fn give_string(out: *mut *mut c_char, s: String) -> Result<(), NeggStatus> {
    let c = CString::new(s).map_err(|_| fail(NeggStatus::Json, "result contains a NUL byte"))?;
    // SAFETY: `out` is valid by the caller's contract.
    unsafe { *out = c.into_raw() };
    Ok(())
}

/// The version of this ABI ([`NEGG_ABI_VERSION`]).
#[unsafe(no_mangle)]
pub extern "C" fn negg_abi_version() -> u32 {
    NEGG_ABI_VERSION
}

/// Opens the roll in `dir` and runs its analysis to completion (pass 1 and
/// the roll pool), so every later call sees a finished roll. Writes
/// nothing to disk.
///
/// On success `*out` is a new handle to free with [`negg_session_free`];
/// on failure `*out` is set to NULL. A failure to pool the roll (for
/// example a frame sidecar with invalid settings) is not a failure to open:
/// the status is Ok, the frames keep their own estimates, and the pooling
/// error is this thread's last error. So Ok with a non-empty
/// [`negg_last_error`] means the roll opened but pooling failed; a clean
/// open leaves the last error empty.
///
/// # Safety
///
/// `dir` is NULL or a NUL-terminated string valid for the call. `out` is
/// NULL or a valid location for one pointer.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_open_roll(
    dir: *const c_char,
    out: *mut *mut NeggSession,
) -> NeggStatus {
    guard(|| {
        if out.is_null() {
            return Err(fail(NeggStatus::Null, "out is NULL"));
        }
        // SAFETY: `out` is non-NULL and writable by the caller's contract.
        unsafe { *out = std::ptr::null_mut() };
        // SAFETY: `dir` is checked inside and valid by the contract.
        let dir = unsafe { c_str(dir, "dir")? };
        let mut session = Session::open_roll(Path::new(dir)).map_err(|e| session_status(&e))?;
        // As `Session::analyse_all`: a pooling failure is not fatal (the
        // frames keep their own estimates), so go on to Done and report it.
        let mut pool_error = None;
        loop {
            match session.analyse_next() {
                Ok(AnalyseStep::Done) => break,
                Ok(_) => {}
                Err(e) => {
                    pool_error.get_or_insert(e.to_string());
                }
            }
        }
        set_error(pool_error.unwrap_or_default());
        let h = Box::new(NeggSession {
            inner: Mutex::new(session),
            poisoned: AtomicBool::new(false),
        });
        // SAFETY: `out` is non-NULL and writable.
        unsafe { *out = Box::into_raw(h) };
        Ok(())
    })
}

/// Frees a handle from [`negg_open_roll`]. NULL is a no-op. Before the
/// handle goes, the session is flushed once more, best effort: an edit a
/// setter committed but could not write (its flush failed) is written now
/// when it can be, and a sidecar that changed on disk behind the session
/// is still never overwritten. Errors are dropped; call [`negg_flush`]
/// first to see them. A poisoned session is not flushed.
///
/// # Safety
///
/// `s` is NULL or a handle from [`negg_open_roll`] not yet freed, and no
/// other thread is using it.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_session_free(s: *mut NeggSession) {
    if s.is_null() {
        return;
    }
    // A panic in a destructor must not reach C either.
    let _ = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: `s` came from `Box::into_raw` and is freed once.
        let h = unsafe { Box::from_raw(s) };
        if !h.poisoned.load(Ordering::SeqCst)
            && let Ok(mut session) = h.inner.lock()
        {
            let _ = session.flush();
        }
        drop(h);
    }));
}

/// Writes every pending edit to the sidecars now (`Session::flush`): the
/// edits whose setter returned an error after committing (its flush
/// failed), and any sidecar a roll edit made out of date. A sidecar that
/// changed on disk behind the session is never overwritten; that frame
/// turns read-only and the status is [`NeggStatus::Session`] with the
/// message naming the file. Calling it again after fixing the cause (for
/// example a full disk) retries the writes.
///
/// # Safety
///
/// `s` is NULL or a live handle.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_flush(s: *mut NeggSession) -> NeggStatus {
    guard(|| with_session(s, |sess| sess.flush().map_err(|e| session_status(&e))))
}

/// Writes the number of frames of the roll to `*out`.
///
/// # Safety
///
/// `s` is NULL or a live handle; `out` is NULL or a valid location for one
/// `u32`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_frame_count(s: *const NeggSession, out: *mut u32) -> NeggStatus {
    guard(|| {
        if out.is_null() {
            return Err(fail(NeggStatus::Null, "out is NULL"));
        }
        let n = with_session(s, |sess| Ok(sess.frame_count()))?;
        // SAFETY: `out` is non-NULL and writable.
        unsafe { *out = n };
        Ok(())
    })
}

/// Renders one preview tile into the caller's buffer, in the tile wire
/// format (48-byte header, then RGBA8). `*len` is always set to the number
/// of bytes the tile needs when it is known. If `cap` is smaller, nothing
/// is written and the status is [`NeggStatus::BufferTooSmall`]; call again
/// with a buffer of `*len` bytes. `buf` may be NULL only when `cap` is 0,
/// as a size query (the tile is still rendered, so a size query costs one
/// full render; the second call renders again).
///
/// # Safety
///
/// `s` is NULL or a live handle. `buf` is NULL (with `cap == 0`) or points
/// to `cap` writable bytes. `len` is NULL or a valid location for one
/// `usize`.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_render_tile(
    s: *mut NeggSession,
    frame: u32,
    level: u32,
    tile_x: u32,
    tile_y: u32,
    buf: *mut u8,
    cap: usize,
    len: *mut usize,
) -> NeggStatus {
    guard(|| {
        if len.is_null() {
            return Err(fail(NeggStatus::Null, "len is NULL"));
        }
        if buf.is_null() && cap > 0 {
            return Err(fail(NeggStatus::Null, "buf is NULL but cap is not 0"));
        }
        let tile = with_session(s, |sess| {
            sess.render_tile(frame, level, tile_x, tile_y)
                .map_err(|e| session_status(&e))
        })?;
        // SAFETY: `len` is non-NULL and writable.
        unsafe { *len = tile.len() };
        if tile.len() > cap {
            return Err(fail(
                NeggStatus::BufferTooSmall,
                format!("the tile needs {} bytes, the buffer has {cap}", tile.len()),
            ));
        }
        // SAFETY: `buf` has `cap >= tile.len() > 0` writable bytes and does
        // not overlap the freshly allocated `tile`.
        unsafe { std::ptr::copy_nonoverlapping(tile.as_ptr(), buf, tile.len()) };
        Ok(())
    })
}

/// Writes the frame's `FrameView` as JSON (snake_case keys, as the
/// sidecars) to `*json`, a string to free with [`negg_string_free`].
/// Opens the frame. `*json` is set to NULL on failure.
///
/// # Safety
///
/// `s` is NULL or a live handle; `json` is NULL or a valid location for one
/// pointer.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_get_stats(
    s: *mut NeggSession,
    frame: u32,
    json: *mut *mut c_char,
) -> NeggStatus {
    guard(|| {
        if json.is_null() {
            return Err(fail(NeggStatus::Null, "json is NULL"));
        }
        // SAFETY: `json` is non-NULL and writable.
        unsafe { *json = std::ptr::null_mut() };
        let view = with_session(s, |sess| {
            sess.frame_view(frame).map_err(|e| session_status(&e))
        })?;
        let text = serde_json::to_string(&view)
            .map_err(|e| fail(NeggStatus::Json, format!("cannot encode the view: {e}")))?;
        // SAFETY: `json` is non-NULL and writable.
        unsafe { give_string(json, text) }
    })
}

/// Commits a frame's `FrameOverrides` (JSON, whole value) and flushes the
/// sidecars. The flush settles any pending re-pool, so the caller never
/// sees a pending pool afterwards.
///
/// The two steps can fail apart. When the commit is refused (invalid
/// overrides, a read-only frame, a sidecar changed on disk) nothing
/// changed. When the commit succeeded but the flush failed (a write error,
/// another sidecar changed on disk), the edit is kept in the session and
/// the status is still [`NeggStatus::Session`]: the edit is not lost, it
/// is written by the next successful [`negg_flush`], setter or
/// [`negg_session_free`]. Reading the frame back with [`negg_get_stats`]
/// shows the committed value either way.
///
/// # Safety
///
/// `s` is NULL or a live handle; `overrides_json` is NULL or a
/// NUL-terminated string valid for the call.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_set_settings(
    s: *mut NeggSession,
    frame: u32,
    overrides_json: *const c_char,
) -> NeggStatus {
    guard(|| {
        if s.is_null() {
            return Err(fail(NeggStatus::Null, "session is NULL"));
        }
        // SAFETY: checked inside; valid by the contract.
        let text = unsafe { c_str(overrides_json, "overrides_json")? };
        let overrides: FrameOverrides = serde_json::from_str(text)
            .map_err(|e| fail(NeggStatus::Json, format!("invalid overrides JSON: {e}")))?;
        with_session(s, |sess| {
            sess.commit_frame(frame, overrides)
                .map_err(|e| session_status(&e))?;
            sess.flush().map_err(|e| session_status(&e))
        })
    })
}

/// Commits the roll's `RollSettings` (JSON, whole value) and flushes the
/// sidecars; see [`negg_set_settings`].
///
/// # Safety
///
/// `s` is NULL or a live handle; `roll_json` is NULL or a NUL-terminated
/// string valid for the call.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_set_roll_settings(
    s: *mut NeggSession,
    roll_json: *const c_char,
) -> NeggStatus {
    guard(|| {
        if s.is_null() {
            return Err(fail(NeggStatus::Null, "session is NULL"));
        }
        // SAFETY: checked inside; valid by the contract.
        let text = unsafe { c_str(roll_json, "roll_json")? };
        let roll: RollSettings = serde_json::from_str(text)
            .map_err(|e| fail(NeggStatus::Json, format!("invalid roll settings JSON: {e}")))?;
        with_session(s, |sess| {
            sess.commit_roll(roll).map_err(|e| session_status(&e))?;
            sess.flush().map_err(|e| session_status(&e))
        })
    })
}

/// Exports one frame (`frame >= 0`) or the whole roll (`frame == -1`) as
/// `negg convert` or `negg batch` would. `format` is 0 for TIFF16 and 1
/// for JPEG. `out_dir` NULL writes beside the sources. `report_json` may be
/// NULL; otherwise it receives the `ExportReport` as JSON (free it with
/// [`negg_string_free`]), also when some frames failed. If any frame
/// failed the status is [`NeggStatus::Session`] and the first error is the
/// last error. An unknown `format` is also [`NeggStatus::Session`], and a
/// `frame` below -1 or above `u32::MAX` is [`NeggStatus::NotFound`].
///
/// # Safety
///
/// `s` is NULL or a live handle; `out_dir` is NULL or a NUL-terminated
/// string valid for the call; `report_json` is NULL or a valid location for
/// one pointer.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_export(
    s: *mut NeggSession,
    frame: i64,
    format: u32,
    out_dir: *const c_char,
    report_json: *mut *mut c_char,
) -> NeggStatus {
    guard(|| {
        if s.is_null() {
            return Err(fail(NeggStatus::Null, "session is NULL"));
        }
        if !report_json.is_null() {
            // SAFETY: non-NULL and writable by the contract.
            unsafe { *report_json = std::ptr::null_mut() };
        }
        let format = match format {
            0 => ExportFormat::Tiff16,
            1 => ExportFormat::Jpeg,
            n => {
                return Err(fail(
                    NeggStatus::Session,
                    format!("unknown export format {n}"),
                ));
            }
        };
        let scope = match frame {
            -1 => ExportScope::Roll,
            f => match u32::try_from(f) {
                Ok(f) => ExportScope::Frame { frame: f },
                Err(_) => {
                    return Err(fail(
                        NeggStatus::NotFound,
                        format!("the roll has no frame {f}"),
                    ));
                }
            },
        };
        let out_dir = if out_dir.is_null() {
            None
        } else {
            // SAFETY: non-NULL, valid by the contract.
            Some(unsafe { c_str(out_dir, "out_dir")? }.to_owned())
        };
        let req = ExportRequest {
            scope,
            format,
            out_dir,
        };
        let report = with_session(s, |sess| {
            sess.export(&req, &mut |_| {})
                .map_err(|e| session_status(&e))
        })?;
        if !report_json.is_null() {
            let text = serde_json::to_string(&report)
                .map_err(|e| fail(NeggStatus::Json, format!("cannot encode the report: {e}")))?;
            // SAFETY: non-NULL and writable.
            unsafe { give_string(report_json, text)? };
        }
        if report.failed > 0 {
            let first = report.errors.first().map_or("", String::as_str);
            return Err(fail(
                NeggStatus::Session,
                format!("{} frame(s) failed to export: {first}", report.failed),
            ));
        }
        Ok(())
    })
}

/// Frees a string returned by negg ([`negg_get_stats`], [`negg_export`]).
/// NULL is a no-op. Never pass any other pointer.
///
/// # Safety
///
/// `p` is NULL or a string returned by negg and not yet freed.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_string_free(p: *mut c_char) {
    if p.is_null() {
        return;
    }
    let _ = catch_unwind(AssertUnwindSafe(|| {
        // SAFETY: `p` came from `CString::into_raw` and is freed once.
        drop(unsafe { CString::from_raw(p) });
    }));
}

/// Copies the message of the last failure on the calling thread into `buf`
/// (at most `cap` bytes including the NUL, truncated if needed) and returns
/// the bytes needed including the NUL. Pass `buf == NULL` with `cap == 0`
/// to ask the size. Returns 1 (just the NUL) when there is no message. A
/// truncated copy may end inside a multi-byte UTF-8 character.
///
/// # Safety
///
/// `buf` is NULL or points to `cap` writable bytes.
#[unsafe(no_mangle)]
pub unsafe extern "C" fn negg_last_error(buf: *mut c_char, cap: usize) -> usize {
    catch_unwind(AssertUnwindSafe(|| {
        LAST_ERROR.with(|e| {
            let msg = e.borrow();
            let bytes = msg.as_bytes();
            let needed = bytes.len() + 1;
            if !buf.is_null() && cap > 0 {
                let n = bytes.len().min(cap - 1);
                // SAFETY: `buf` has `cap >= n + 1` writable bytes.
                unsafe {
                    std::ptr::copy_nonoverlapping(bytes.as_ptr(), buf.cast::<u8>(), n);
                    *buf.add(n) = 0;
                }
            }
            needed
        })
    }))
    .unwrap_or(1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_panic_is_caught_and_poisons_the_session() {
        // A real session is needed only for the handle; the closure panics.
        let dir = std::env::temp_dir().join(format!("negg-ffi-panic-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let session = Session::open_roll(&dir).unwrap();
        let h = NeggSession {
            inner: Mutex::new(session),
            poisoned: AtomicBool::new(false),
        };
        let r: Result<(), NeggStatus> = with_session(&h, |_| panic!("boom"));
        assert_eq!(r, Err(NeggStatus::Panic));
        assert!(h.poisoned.load(Ordering::SeqCst));
        let r: Result<(), NeggStatus> = with_session(&h, |_| Ok(()));
        assert_eq!(r, Err(NeggStatus::Poisoned));
        let mut n = 0u32;
        assert_eq!(
            unsafe { negg_frame_count(&h, &mut n) },
            NeggStatus::Poisoned
        );
        let mut buf = [0 as c_char; 64];
        let needed = unsafe { negg_last_error(buf.as_mut_ptr(), buf.len()) };
        assert!(needed > 1);
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn guard_catches_panics() {
        assert_eq!(guard(|| panic!("boom")), NeggStatus::Panic);
        assert_eq!(guard(|| Ok(())), NeggStatus::Ok);
    }
}
